#!/usr/bin/env bash
# install-opencode.sh - install harmonia into an OpenCode config directory.
#
# Places two things under the target (design D3 of the multi-harness-install
# task): <target>/harmonia, an engine home mirroring the repo's bin/, core/,
# and skills/; and <target>/commands/harmonia-<name>.md, one generated
# OpenCode command file per skills/<name>/SKILL.md. Placed *.md and *.yaml
# are rewritten on the way (D4): the closed-literal dollar-brace
# CLAUDE_PLUGIN_ROOT reference becomes the absolute engine home (the exact
# byte pattern is in the sed below - spelling it out here would put the one
# string the install gate greps for into a byte-copied file), and the
# /harmonia: command spelling becomes /harmonia- (OpenCode commands have no
# namespace separator). *.sh files ship byte-copied - they resolve their own
# location when the plugin root variable is unset.
#
# Target resolution: --target beats OPENCODE_CONFIG_DIR beats
# $HOME/.config/opencode. Re-running converges to a fresh install: the
# engine home is rebuilt via temp-build-and-swap, and only command files
# carrying the generation marker are ever removed (D5). No live harness is
# invoked and no OpenCode config file is edited.
set -euo pipefail

MARKER='<!-- generated by harmonia install; re-created on every run; do not edit -->'

usage() {
  echo "usage: install-opencode.sh [--target <dir>]" >&2
  echo "  --target <dir>  install into <dir> (default: \$OPENCODE_CONFIG_DIR, else \$HOME/.config/opencode)" >&2
}

die() {
  echo "install-opencode: $*" >&2
  exit 1
}

target=""
target_set=0
while [ $# -gt 0 ]; do
  case "$1" in
    --target)
      shift
      target="${1-}"
      target_set=1
      if [ $# -gt 0 ]; then shift; fi
      ;;
    *)
      echo "install-opencode: unknown argument: $1" >&2
      usage
      exit 2
      ;;
  esac
done

if [ "$target_set" -eq 0 ]; then
  target="${OPENCODE_CONFIG_DIR:-${HOME:-}/.config/opencode}"
fi
if [ -z "$target" ]; then
  die "no target: pass --target <dir> or set OPENCODE_CONFIG_DIR"
fi

# Normalize before splicing anywhere: a relative or trailing-slashed target
# would embed a cwd-dependent or double-slashed path into every placed body.
mkdir -p -- "$target"
target="$(cd -- "$target" && pwd)"
if [ "$target" = "/" ] || [ "$target" = "//" ]; then
  die "refusing target $target: will not install into the filesystem root; pick a different --target"
fi
case "$target" in
  *[!A-Za-z0-9._/-]*)
    die "target '$target' has an unsupported character; placed bodies embed this path in unquoted shell instructions, so pick a target using only [A-Za-z0-9._/-]"
    ;;
esac

src="$(cd -- "$(dirname -- "${BASH_SOURCE[0]}")/.." && pwd)"
engine_home="$target/harmonia"
cmd_dir="$target/commands"

# Stale temp trees from interrupted runs; -f keeps the unmatched glob silent.
rm -rf -- "$target"/harmonia.new.*

# Pre-flight, before anything is placed. The engine home is ours only if it
# bears the signature; anything else is refused intact.
if [ -e "$engine_home" ] && [ ! -f "$engine_home/core/RULES.md" ]; then
  die "refusing: $engine_home exists but is not a harmonia install (no core/RULES.md); move it aside or pick another --target"
fi

# A file at a name this run will generate is ours only if it carries the
# marker; an unmarked one is the user's, so abort before touching anything.
conflicts=""
for d in "$src"/skills/*/; do
  name="$(basename -- "$d")"
  f="$cmd_dir/harmonia-$name.md"
  if [ -f "$f" ] && ! grep -qF -- "$MARKER" "$f"; then
    conflicts="$conflicts  $f"$'\n'
  fi
done
if [ -n "$conflicts" ]; then
  printf '%s\n%s' "install-opencode: refusing: existing command files are not harmonia-generated (no marker); move them aside:" "$conflicts" >&2
  exit 1
fi

# Temp-build-and-swap: the old engine home is removed only once the new one
# is fully staged, so an interrupted run can never wedge a later one.
tmp="$engine_home.new.$$"
trap 'rm -rf -- "$tmp"' EXIT
mkdir -p -- "$tmp"
cp -R -- "$src/bin" "$src/core" "$src/skills" "$tmp/"

# T1 + T2 on placed *.md/*.yaml. The engine home is spliced literally:
# backslash, & (whole-match in a sed replacement), and the | delimiter are
# sed-escaped; every other shell-unsafe character was refused by the charset
# guard above, so no metacharacter reaches an unquoted command-body instruction.
esc="$(printf '%s' "$engine_home" | sed 's/[|\\&]/\\&/g')"
find "$tmp" -type f \( -name '*.md' -o -name '*.yaml' \) | while IFS= read -r f; do
  sed -e 's|[$]{CLAUDE_PLUGIN_ROOT}|'"$esc"'|g' -e 's|/harmonia:|/harmonia-|g' "$f" > "$f.new"
  cat -- "$f.new" > "$f"
  rm -f -- "$f.new"
done

if [ -e "$engine_home" ]; then
  rm -rf -- "$engine_home"
fi
mv -- "$tmp" "$engine_home"

# Command files: collect every marked harmonia-*.md (stale ones from removed
# skills included), then generate one file per placed skill. Frontmatter is
# re-headed to just the description (the filename carries the name); the
# marker sits on the first body line so the frontmatter stays at byte 0.
mkdir -p -- "$cmd_dir"
for f in "$cmd_dir"/harmonia-*.md; do
  if [ -f "$f" ] && grep -qF -- "$MARKER" "$f"; then
    rm -f -- "$f"
  fi
done
count=0
for d in "$engine_home"/skills/*/; do
  name="$(basename -- "$d")"
  skill="${d%/}/SKILL.md"
  desc="$(awk '/^---$/{n++; next} n==1 && /^description: /{print; exit}' "$skill")"
  {
    printf -- '---\n%s\n---\n%s\n' "$desc" "$MARKER"
    awk 'b{print; next} /^---$/{if(++n==2) b=1}' "$skill"
  } > "$cmd_dir/harmonia-$name.md"  # harmonia:exempt kcov cannot attribute this brace-group redirect closer; the body it writes is pinned by the body-completeness test
  count=$((count + 1))
done

echo "harmonia installed for OpenCode"
echo "  engine home: $engine_home"
echo "  commands:    $count files at $cmd_dir/harmonia-<name>.md, each typed as /harmonia-<name>"
echo "not ported on OpenCode (see the README's OpenCode section for both):"
echo "  - roster subagent dispatch: stage procedures run in the main session; charters stay readable at $engine_home/core/charters/"
echo "  - session-start context injection: the first harmonia command reads $engine_home/core/RULES.md itself"
